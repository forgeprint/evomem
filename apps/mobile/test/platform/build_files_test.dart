import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// The smallest API level the plugins in this build will link against.
///
/// Read from the pub cache on 2026-10-10: record_android 2.2.0 sets
/// `minSdk = 24` in its android/build.gradle, and flutter_secure_storage
/// 11.2.0 does the same. Gradle fails the build when the application's floor
/// is below a library's, so this is not advice.
const minimumAndroidSdk = 24;

/// The one application identity, on both platforms.
const bundleIdentifier = 'com.evomem.mobile';

String _read(String path) {
  final file = File(path);
  if (!file.existsSync()) {
    fail('$path is missing: the platform build files are not there');
  }
  return file.readAsStringSync();
}

void main() {
  // These files are generated by `flutter create`, which hands back its own
  // defaults every time it runs: an application id derived from the package
  // name, a minSdk inherited from whatever Flutter currently defaults to,
  // and a manifest with a `package` attribute. Each of those was wrong here,
  // and none of them fails a Dart build — they fail a Gradle build on a
  // machine with an Android SDK, or they ship two identities for one app.
  group('the Android build files', () {
    test('name the same identity the iOS build does', () {
      final gradle = _read('android/app/build.gradle.kts');

      expect(gradle, contains('namespace = "$bundleIdentifier"'));
      expect(gradle, contains('applicationId = "$bundleIdentifier"'));

      final pbxproj = _read('ios/Runner.xcodeproj/project.pbxproj');
      expect(
        pbxproj,
        contains('PRODUCT_BUNDLE_IDENTIFIER = $bundleIdentifier;'),
        reason: 'the app would install under two different identities',
      );
    });

    test('pin minSdk high enough for the plugins, as a number', () {
      final gradle = _read('android/app/build.gradle.kts');

      final match = RegExp(r'minSdk\s*=\s*(\S+)').firstMatch(gradle);
      expect(match, isNotNull, reason: 'no minSdk at all');

      final value = match!.group(1)!;
      expect(
        int.tryParse(value),
        isNotNull,
        reason:
            'minSdk is $value, so the floor is whatever Flutter defaults to '
            'today; a Flutter upgrade that lowered it would break the build '
            'instead of changing a number somebody chose',
      );
      expect(int.parse(value), greaterThanOrEqualTo(minimumAndroidSdk));
    });

    test('carry no package attribute, which is now a build error', () {
      final manifest = _read('android/app/src/main/AndroidManifest.xml');

      expect(
        manifest,
        isNot(contains('package="')),
        reason: 'the Android Gradle Plugin refuses a manifest package',
      );
    });

    test('ask for the microphone, and have an activity to ask from', () {
      expect(
        _read('android/app/src/main/AndroidManifest.xml'),
        contains('android.permission.RECORD_AUDIO'),
      );
      // The manifest names `.MainActivity`, which resolves against the
      // namespace — so the class has to live in that package and not in the
      // one `flutter create` generated.
      expect(
        File(
          'android/app/src/main/kotlin/'
          '${bundleIdentifier.replaceAll('.', '/')}/MainActivity.kt',
        ).existsSync(),
        isTrue,
        reason: 'the launcher activity is not where the manifest says',
      );
    });
  });

  group('the iOS build files', () {
    test('explain the microphone before iOS is asked for it', () {
      // Without this key iOS does not show a prompt, it refuses outright.
      expect(
        _read('ios/Runner/Info.plist'),
        contains('NSMicrophoneUsageDescription'),
      );
    });

    test('take the bundle id from the build setting, not a second copy', () {
      expect(
        _read('ios/Runner/Info.plist'),
        contains(r'<string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>'),
        reason: 'two places to change an identity means one gets forgotten',
      );
    });

    test('stay at or above the deployment target record_ios declares', () {
      // record_ios 2.1.1 declares iOS 12.0 in its podspec and Package.swift
      // (pub cache, 2026-10-10). The project is higher, which is allowed;
      // lower is what would fail.
      final targets = RegExp('IPHONEOS_DEPLOYMENT_TARGET = ([0-9.]+);')
          .allMatches(_read('ios/Runner.xcodeproj/project.pbxproj'))
          .map((m) => double.parse(m.group(1)!))
          .toSet();

      expect(targets, isNotEmpty, reason: 'no deployment target is set');
      for (final target in targets) {
        expect(target, greaterThanOrEqualTo(12.0));
      }
    });
  });
}
